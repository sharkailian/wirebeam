/**
 * qrdec.mjs — an INDEPENDENT QR Code decoder (ISO/IEC 18004), written from
 * scratch for the purpose of auditing `dropsend/src/lib/qr.ts`.
 *
 * Nothing here is copied from qr.ts: GF(256) arithmetic uses shift-and-xor
 * (no log/antilog tables), BCH validation uses plain GF(2) polynomial
 * division over a brute-forced code, the block structure is *recovered from
 * the data itself* by searching (blocks, ec-per-block) pairs until the
 * Reed-Solomon syndromes vanish, and the finder/grid geometry is measured
 * from the pixel matrix with run-length scanning.
 *
 * Assumptions the author is aware of (stated explicitly in the report):
 *  A1. Input matrices are exact (1 module == 1 boolean); no binarisation.
 *  A2. Bit index convention for format info: bit 0 is the LSB of the 15-bit
 *      format word; the module order follows Figure 25 of the spec as
 *      (8,0)..(8,5),(8,7),(8,8),(7,8),(5,8)..(0,8) -> bit 0 .. bit 14.
 *  A3. Rule-3 penalty out-of-bounds handling is ambiguous in the spec; both
 *      readings are computed by penalty() below.
 */

// ---------------------------------------------------------------------------
// GF(256) — primitive polynomial x^8+x^4+x^3+x^2+1 (0x11D), table-free
// ---------------------------------------------------------------------------

const GF_PRIM = 0x11d;

export function gfMul(a, b) {
  let x = a & 0xff;
  let y = b & 0xff;
  let acc = 0;
  while (y !== 0) {
    if (y & 1) acc ^= x;
    y >>>= 1;
    x <<= 1;
    if (x & 0x100) x ^= GF_PRIM;
  }
  return acc & 0xff;
}

/** alpha^i in GF(256). */
export function gfAlpha(i) {
  let v = 1;
  for (let k = 0; k < ((i % 255) + 255) % 255; k++) v = gfMul(v, 2);
  return v;
}

/** Reed-Solomon syndromes S_0..S_{t-1} of a full block (data ++ ec). */
export function rsSyndromes(block, t) {
  const out = [];
  for (let j = 0; j < t; j++) {
    const root = gfAlpha(j);
    let acc = 0;
    for (let k = 0; k < block.length; k++) acc = gfMul(acc, root) ^ block[k];
    out.push(acc);
  }
  return out;
}

// ---------------------------------------------------------------------------
// BCH codes as plain GF(2) polynomial multiples — independent construction
// ---------------------------------------------------------------------------

/** Remainder of `value` modulo generator `gen` (whose degree is genDeg). */
function gf2Mod(value, gen, genDeg) {
  let v = value;
  for (let i = 30; i >= genDeg; i--) {
    if ((v >>> i) & 1) v ^= gen << (i - genDeg);
  }
  return v >>> 0;
}

/**
 * Enumerate every codeword of the binary BCH code generated by `gen` with
 * codeword length `n`: { v : deg v < n, gen | v }. Cost 2^n, so only used for
 * n = 15 (format) and n = 18 (version).
 */
function enumerateCode(gen, genDeg, n) {
  const code = [];
  for (let v = 0; v < 1 << n; v++) if (gf2Mod(v, gen, genDeg) === 0) code.push(v);
  return code;
}

const FORMAT_MASK = 0x5412;
const FORMAT_CODE = enumerateCode(0x537, 10, 15); // 32 valid 15-bit format words
const VERSION_CODE = enumerateCode(0x1f25, 12, 18); // 64 valid 18-bit version words

function popcount(v) {
  let c = 0;
  while (v) {
    c += v & 1;
    v >>>= 1;
  }
  return c;
}

/** Minimum-distance decode against a code of length n (distance 3 correctable). */
function bchDecode(received, code, n) {
  let best = -1;
  let bestD = 99;
  for (const c of code) {
    const d = popcount(c ^ received);
    if (d < bestD) {
      bestD = d;
      best = c;
    }
  }
  return { codeword: best, distance: bestD, ok: bestD <= 3, exact: bestD === 0 };
}

/** Format-info data bits -> EC level, per Table 25 (L=01, M=00, Q=11, H=10). */
const FORMAT_EC = { 0b01: 'L', 0b00: 'M', 0b11: 'Q', 0b10: 'H' };

function formatBitsOf(data5) {
  // Non-authoritative helper used only to build the *expected* word for
  // candidate-mask rebuilds in the mask audit: multiply the data polynomial by
  // x^10 and take the GF(2) remainder, then apply the 0x5412 mask.
  const word = (data5 << 10) | gf2Mod(data5 << 10, 0x537, 10);
  return (word ^ FORMAT_MASK) & 0x7fff;
}
export { formatBitsOf };

