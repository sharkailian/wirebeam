/**
 * Decode a module matrix. `m` is boolean[][] (true = dark).
 * Returns a detailed report; throws only on unrecoverable geometry failure.
 */
export function decodeMatrix(m, opts = {}) {
  const report = { notes: [] };
  const g = locateGrid(m);
  report.grid = g;
  if (!g || g.partial) throw new Error('finder patterns not located');
  const grid = cropGrid(m, g);
  if (!grid) throw new Error(`module pitch ${g.unit} is not ~1`);
  report.version = (g.size - 17) / 4;
  if (!Number.isInteger(report.version) || report.version < 1 || report.version > 40) {
    throw new Error(`implausible size ${g.size}`);
  }
  const version = report.version;
  const size = versionSize(version);

  // --- format information, both copies ---
  const f1 = decodeFormatCopy(grid, FORMAT_COPY1);
  const f2 = decodeFormatCopy(grid, formatCopy2(size));
  report.format = { copy1: f1, copy2: f2, agree: f1.data5 === f2.data5, bothExact: f1.exact && f2.exact };
  if (!f1.ok || !f2.ok || !report.format.agree) {
    throw new Error(`format info not BCH-decodable / inconsistent: ${JSON.stringify(report.format)}`);
  }
  const mask = f1.mask;
  const ec = f1.ec;
  report.mask = mask;
  report.ec = ec;

  // --- version information (v >= 7), both copies ---
  if (version >= 7) {
    const vr = (which) => {
      const raw = readBits(grid, versionPositions(size, which));
      const d = bchDecode(raw, VERSION_CODE, 18);
      return { raw, distance: d.distance, version: d.codeword >>> 12, ok: d.ok, exact: d.exact };
    };
    const a = vr('tr');
    const b = vr('bl');
    report.versionInfo = { tr: a, bl: b, agree: a.version === b.version, matches: a.version === version };
    if (!a.ok || !b.ok || a.version !== b.version || a.version !== version) {
      throw new Error(`version info mismatch: ${JSON.stringify(report.versionInfo)}`);
    }
  }

  // --- structure checks ---
  const fn = functionMap(version);
  let rawModules = 0;
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) if (!fn[y][x]) rawModules++;
  report.rawDataModules = rawModules;
  report.totalCodewords = Math.floor(rawModules / 8);
  report.remainderBits = rawModules % 8;

  // --- alignment pattern spot check (independent of the table) ---
  const ac = alignmentCenters(version);
  let alignChecked = 0;
  let alignBad = 0;
  const alignMismatch = [];
  for (const cy of ac) for (const cx of ac) {
    const nearFinder = (cx === 6 && cy === 6) || (cx === 6 && cy === size - 7) || (cx === size - 7 && cy === 6);
    if (nearFinder) continue;
    for (let dy = -2; dy <= 2; dy++) for (let dx = -2; dx <= 2; dx++) {
      const want = Math.max(Math.abs(dx), Math.abs(dy)) !== 1;
      alignChecked++;
      if (grid[cy + dy][cx + dx] !== want) {
        alignBad++;
        alignMismatch.push([cx + dx, cy + dy]);
      }
    }
  }
  report.alignment = { patterns: ac.length * ac.length - (version === 1 ? 0 : 3), checked: alignChecked, bad: alignBad, mismatch: alignMismatch.slice(0, 8) };

  // --- unmask + zigzag read ---
  const un = unmask(grid, version, mask);
  const bits = readRawBits(un, version);
  if (bits.length !== rawModules) {
    throw new Error(`bit stream length ${bits.length} != raw modules ${rawModules}`);
  }
  const total = Math.floor(rawModules / 8);
  const codewords = [];
  for (let i = 0; i < total; i++) {
    let v = 0;
    for (let k = 0; k < 8; k++) v = (v << 1) | bits[i * 8 + k];
    codewords.push(v);
  }
  const rem = bits.slice(total * 8);
  report.remainderBitValues = rem;
  report.remainderAllZero = rem.every((b) => b === 0);
  report.codewords = codewords;

  // --- block structure: recovery from data, plus the declared table ---
  const recovery = recoverBlockStructure(codewords, version);
  report.recoveredStructures = recovery.solutions;
  report.zeroSyndromeStructures = recovery.zeroSyndromeCount;

  let structure = null;
  if (opts.numBlocks && opts.ecLen) {
    structure = { numBlocks: opts.numBlocks, ecLen: opts.ecLen, source: 'table' };
  } else if (recovery.solutions.length === 1) {
    structure = { numBlocks: recovery.solutions[0].numBlocks, ecLen: recovery.solutions[0].ecLen, source: 'recovered' };
  }
  if (!structure) throw new Error(`ambiguous block structure: ${JSON.stringify(recovery.solutions)}`);
  const de = deinterleave(codewords, structure.numBlocks, structure.ecLen);
  report.structure = { ...structure, numShortBlocks: de.numShort, shortDataLen: de.shortDataLen, dataCodewords: de.dataEnd };

  // --- RS syndrome check on every block ---
  report.syndromes = [];
  let synBad = 0;
  for (let b = 0; b < de.blocks.length; b++) {
    const syn = rsSyndromes(de.blocks[b], structure.ecLen);
    const nonzero = syn.filter((s) => s !== 0).length;
    if (nonzero) synBad++;
    report.syndromes.push({ block: b, len: de.blocks[b].length, nonzero, first: syn.slice(0, 4) });
  }
  report.syndromeFailures = synBad;
  report.syndromeSummary = `${de.blocks.length} blocks x ${structure.ecLen} syndromes, ${synBad} block(s) with non-zero syndrome`;

  // --- payload (from the DE-INTERLEAVED data codewords, in block order) ---
  const dataCw = dataCodewordsOf(de);
  const dataBits = bitsOf(dataCw);
  const frame = parseByteMode(dataBits, version);
  report.frame = { mode: frame.mode, count: frame.count, bitOffset: frame.bitOffset, countBits: frame.countBits };
  if (frame.error) throw new Error(frame.error);
  const pad = validatePadding(dataBits, frame.bitOffset, de.dataEnd);
  report.padding = pad;
  report.bytes = frame.bytes;
  try {
    report.text = dec.decode(Uint8Array.from(frame.bytes));
  } catch (e) {
    report.text = null;
    report.notes.push('payload is not valid UTF-8: ' + e.message);
  }
  report.ok =
    report.syndromeFailures === 0 &&
    report.remainderAllZero &&
    pad.ok &&
    frame.count === frame.bytes.length &&
    report.text !== null;
  return report;
}

