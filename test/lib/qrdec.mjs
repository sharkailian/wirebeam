/**
 * The four penalty rules. `edgeLight` controls the ambiguous rule-3 reading:
 * true  = modules outside the symbol count as light (ZXing-like)
 * false = an out-of-bounds 4-module run does not satisfy the rule (Nayuki-like)
 */
export function penalty(m, edgeLight) {
  const size = m.length;
  let score = 0;
  // Rule 1
  for (let y = 0; y < size; y++) {
    let run = 1;
    for (let x = 1; x < size; x++) {
      if (m[y][x] === m[y][x - 1]) {
        run++;
        if (run === 5) score += 3;
        else if (run > 5) score += 1;
      } else run = 1;
    }
  }
  for (let x = 0; x < size; x++) {
    let run = 1;
    for (let y = 1; y < size; y++) {
      if (m[y][x] === m[y - 1][x]) {
        run++;
        if (run === 5) score += 3;
        else if (run > 5) score += 1;
      } else run = 1;
    }
  }
  // Rule 2
  for (let y = 0; y + 1 < size; y++) {
    for (let x = 0; x + 1 < size; x++) {
      const c = m[y][x];
      if (c === m[y][x + 1] && c === m[y + 1][x] && c === m[y + 1][x + 1]) score += 3;
    }
  }
  // Rule 3
  // edgeLight === true : modules outside the symbol are the quiet zone, i.e.
  //                      light (the reading used by ZXing's isWhiteHorizontal,
  //                      which clamps the window to the symbol bounds).
  // edgeLight === false: an out-of-bounds 4-module window does not satisfy the
  //                      rule at all (the reading used by qr.ts).
  const light = (get, from, to) => {
    if (!edgeLight && (from < 0 || to > size)) return false;
    for (let i = from; i < to; i++) {
      if (i < 0 || i >= size) continue;
      if (get(i)) return false;
    }
    return true;
  };
  const scan = (get) => {
    for (let i = 0; i + 6 < size; i++) {
      if (get(i) && !get(i + 1) && get(i + 2) && get(i + 3) && get(i + 4) && !get(i + 5) && get(i + 6)) {
        if (light(get, i - 4, i) || light(get, i + 7, i + 11)) score += 40;
      }
    }
  };
  for (let y = 0; y < size; y++) scan((i) => m[y][i]);
  for (let x = 0; x < size; x++) scan((i) => m[i][x]);
  // Rule 4
  let dark = 0;
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) if (m[y][x]) dark++;
  const total = size * size;
  const k = Math.ceil((Math.abs(dark * 20 - total * 10)) / total) - 1;
  score += Math.max(0, k) * 10;
  return score;
}
