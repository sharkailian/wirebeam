export function versionSize(version) {
  return version * 4 + 17;
}

/** Alignment pattern centre coordinates (spec Annex E table generator). */
export function alignmentCenters(version) {
  if (version === 1) return [];
  const n = Math.floor(version / 7) + 2;
  const step = version === 32 ? 26 : Math.ceil((version * 4 + 4) / (n * 2 - 2)) * 2;
  const pos = [6];
  for (let p = version * 4 + 10; pos.length < n; p -= step) pos.splice(1, 0, p);
  return pos;
}

/**
 * Function-module map built from the spec's pattern definitions (finders +
 * separators, timing, alignment, format areas, version areas, dark module).
 */
export function functionMap(version) {
  const size = versionSize(version);
  const f = Array.from({ length: size }, () => new Array(size).fill(false));
  const mark = (x, y) => {
    if (x >= 0 && y >= 0 && x < size && y < size) f[y][x] = true;
  };
  // Finder patterns + separators: 8x8 blocks in three corners.
  for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) {
    mark(x, y);
    mark(size - 1 - x, y);
    mark(x, size - 1 - y);
  }
  // Timing patterns.
  for (let i = 0; i < size; i++) {
    mark(6, i);
    mark(i, 6);
  }
  // Alignment patterns (skip the three that would collide with finders).
  const ac = alignmentCenters(version);
  for (const cy of ac) for (const cx of ac) {
    const nearFinder =
      (cx === 6 && cy === 6) || (cx === 6 && cy === size - 7) || (cx === size - 7 && cy === 6);
    if (nearFinder) continue;
    for (let dy = -2; dy <= 2; dy++) for (let dx = -2; dx <= 2; dx++) mark(cx + dx, cy + dy);
  }
  // Format information areas.
  for (let i = 0; i <= 8; i++) {
    mark(8, i);
    mark(i, 8);
  }
  for (let i = 0; i < 8; i++) {
    mark(size - 1 - i, 8);
    mark(8, size - 1 - i);
  }
  mark(8, size - 8); // always-dark module
  // Version information areas (v >= 7).
  if (version >= 7) {
    for (let i = 0; i < 6; i++) for (let j = 0; j < 3; j++) {
      mark(size - 11 + j, i);
      mark(i, size - 11 + j);
    }
  }
  return f;
}

// ---------------------------------------------------------------------------
// Finder detection / grid derivation
// ---------------------------------------------------------------------------

function runsOfRow(m, y) {
  const W = m[y].length;
  const out = [];
  let start = 0;
  for (let x = 1; x <= W; x++) {
    if (x === W || m[y][x] !== m[y][start]) {
      out.push({ dark: m[y][start], start, len: x - start });
      start = x;
    }
  }
  return out;
}

function runsOfCol(m, x) {
  const H = m.length;
  const out = [];
  let start = 0;
  for (let y = 1; y <= H; y++) {
    if (y === H || m[y][x] !== m[start][x]) {
      out.push({ dark: m[start][x], start, len: y - start });
      start = y;
    }
  }
  return out;
}

function isFinderRatio(runs, i) {
  const r = [runs[i], runs[i + 1], runs[i + 2], runs[i + 3], runs[i + 4]];
  if (!r[0].dark || r[1].dark || !r[2].dark || r[3].dark || !r[4].dark) return null;
  const span = r[0].len + r[1].len + r[2].len + r[3].len + r[4].len;
  const unit = span / 7;
  if (unit < 1) return null;
  const tol = unit * 0.6 + 0.01;
  const want = [1, 1, 3, 1, 1];
  for (let k = 0; k < 5; k++) if (Math.abs(r[k].len - want[k] * unit) > tol) return null;
  return { unit, spanStart: r[0].start, spanEnd: r[4].start + r[4].len - 1 };
}

/** Verify a candidate finder centre by template match at the given pitch. */
function verifyFinder(m, cx, cy, unit) {
  const H = m.length;
  const W = m[0].length;
  let checked = 0;
  let bad = 0;
  for (let dy = -3; dy <= 3; dy++) {
    for (let dx = -3; dx <= 3; dx++) {
      const py = Math.round(cy + dy * unit);
      const px = Math.round(cx + dx * unit);
      if (py < 0 || px < 0 || py >= H || px >= W) continue;
      const ring = Math.max(Math.abs(dx), Math.abs(dy));
      const want = ring !== 2; // 3x3 dark core + dark outer ring, light at ring 2
      checked++;
      if (m[py][px] !== want) bad++;
    }
  }
  return { checked, bad, ok: bad === 0 && checked >= 40 };
}

/**
 * Locate the three finder patterns in a module-exact matrix and derive the
 * module pitch + grid origin. Returns null when no finder pair is found.
 */
export function locateGrid(m) {
  const H = m.length;
  const W = m[0].length;
  const hits = [];
  for (let y = 0; y < H; y++) {
    const runs = runsOfRow(m, y);
    for (let i = 0; i + 4 < runs.length; i++) {
      const r = isFinderRatio(runs, i);
      if (!r) continue;
      const cx = (r.spanStart + r.spanEnd) / 2;
      // vertical confirmation at the candidate column
      const colRuns = runsOfCol(m, Math.round(cx));
      let vertical = null;
      for (let k = 0; k + 4 < colRuns.length; k++) {
        const v = isFinderRatio(colRuns, k);
        if (v && Math.abs((v.spanStart + v.spanEnd) / 2 - y) <= r.unit * 2) {
          vertical = v;
          break;
        }
      }
      if (!vertical) continue;
      const unit = (r.unit + vertical.unit) / 2;
      const cy = (vertical.spanStart + vertical.spanEnd) / 2;
      const v = verifyFinder(m, cx, cy, unit);
      if (!v.ok) continue;
      hits.push({ cx, cy, unit, rows: 1 });
    }
  }
  if (hits.length === 0) return null;
  // Cluster hits that describe the same finder.
  const clusters = [];
  for (const h of hits) {
    let c = clusters.find(
      (cl) => Math.abs(cl.cx - h.cx) <= h.unit * 1.5 && Math.abs(cl.cy - h.cy) <= h.unit * 1.5,
    );
    if (!c) {
      c = { cx: h.cx, cy: h.cy, unit: h.unit, n: 1 };
      clusters.push(c);
    } else {
      c.cx = (c.cx * c.n + h.cx) / (c.n + 1);
      c.cy = (c.cy * c.n + h.cy) / (c.n + 1);
      c.unit = (c.unit * c.n + h.unit) / (c.n + 1);
      c.n++;
    }
  }
  if (clusters.length < 3) return { partial: true, clusters };
  // TL = topmost then leftmost; TR = same row band, rightmost; BL = leftmost column, bottom.
  clusters.sort((a, b) => a.cy - b.cy || a.cx - b.cx);
  const tl = clusters[0];
  const sameRow = clusters.filter((c) => Math.abs(c.cy - tl.cy) <= tl.unit * 3 && c !== tl);
  const tr = sameRow.sort((a, b) => b.cx - a.cx)[0];
  const bottom = clusters.filter((c) => c.cy > tl.cy + tl.unit * 3);
  const bl = bottom.sort((a, b) => a.cx - b.cx)[0];
  if (!tr || !bl) return { partial: true, clusters };
  const unit = (tl.unit + tr.unit + bl.unit) / 3;
  const spanX = (tr.cx - tl.cx) / unit; // == size - 7
  const spanY = (bl.cy - tl.cy) / unit;
  const size = Math.round((spanX + spanY) / 2) + 7;
  const originX = Math.round(tl.cx - 3 * unit);
  const originY = Math.round(tl.cy - 3 * unit);
  return {
    partial: false,
    unit,
    size,
    originX,
    originY,
    finders: { tl, tr, bl },
    spanX,
    spanY,
  };
}

/** Crop a module-exact sub-matrix using a located grid. */
export function cropGrid(m, g) {
  const size = g.size;
  if (g.unit < 0.9 || g.unit > 1.1) return null;
  const out = [];
  for (let y = 0; y < size; y++) {
    const row = [];
    for (let x = 0; x < size; x++) {
      const py = Math.round(g.originY + y * g.unit);
      const px = Math.round(g.originX + x * g.unit);
      const src = m[py]?.[px];
      row.push(src === undefined ? null : src);
    }
    out.push(row);
  }
  return out;
}

