/** Read the raw module stream in zigzag order, skipping the timing column. */
export function readRawBits(m, version) {
  const size = versionSize(version);
  const fn = functionMap(version);
  const bits = [];
  // Column pairs counted from the right; pair 0 runs upward. The vertical
  // timing column (x = 6) is skipped, which shifts the pairs left of it.
  let pairIndex = 0;
  for (let right = size - 1; right >= 1; right -= 2) {
    if (right === 6) right = 5;
    const upward = pairIndex % 2 === 0;
    for (let step = 0; step < size; step++) {
      const y = upward ? size - 1 - step : step;
      for (const x of [right, right - 1]) {
        if (!fn[y][x]) bits.push(m[y][x] ? 1 : 0);
      }
    }
    pairIndex++;
  }
  return bits;
}

export function maskBitFn(mask, x, y) {
  switch (mask) {
    case 0: return (y + x) % 2 === 0;
    case 1: return y % 2 === 0;
    case 2: return x % 3 === 0;
    case 3: return (y + x) % 3 === 0;
    case 4: return (Math.floor(y / 2) + Math.floor(x / 3)) % 2 === 0;
    case 5: return ((y * x) % 2) + ((y * x) % 3) === 0;
    case 6: return (((y * x) % 2) + ((y * x) % 3)) % 2 === 0;
    case 7: return (((y + x) % 2) + ((y * x) % 3)) % 2 === 0;
    default: throw new RangeError('bad mask ' + mask);
  }
}

export function unmask(m, version, mask) {
  const size = versionSize(version);
  const fn = functionMap(version);
  const out = Array.from({ length: size }, () => new Array(size).fill(false));
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      out[y][x] = fn[y][x] ? m[y][x] : m[y][x] !== maskBitFn(mask, x, y);
    }
  }
  return out;
}

/**
 * De-interleave an interleaved codeword stream into (data, ec) blocks.
 * Short blocks come first in the standard; they contribute one fewer data
 * codeword in the final interleaving round.
 */
export function deinterleave(codewords, numBlocks, ecLen) {
  const total = codewords.length;
  if (ecLen * numBlocks >= total) return null;
  const shortBlockLen = Math.floor(total / numBlocks);
  const numShort = numBlocks - (total % numBlocks);
  const shortDataLen = shortBlockLen - ecLen;
  if (shortDataLen < 1) return null;
  const dataLens = [];
  for (let b = 0; b < numBlocks; b++) dataLens.push(shortDataLen + (b < numShort ? 0 : 1));
  const maxDataLen = shortDataLen + (numShort < numBlocks ? 1 : 0);
  const blocks = Array.from({ length: numBlocks }, () => []);
  let p = 0;
  for (let i = 0; i < maxDataLen; i++) {
    for (let b = 0; b < numBlocks; b++) {
      if (i < dataLens[b]) {
        if (p >= total) return null;
        blocks[b].push(codewords[p++]);
      }
    }
  }
  const dataEnd = p;
  for (let i = 0; i < ecLen; i++) {
    for (let b = 0; b < numBlocks; b++) {
      if (p >= total) return null;
      blocks[b].push(codewords[p++]);
    }
  }
  if (p !== total) return null;
  return { blocks, dataLens, numShort, shortBlockLen, shortDataLen, ecLen, dataEnd };
}

// ---------------------------------------------------------------------------
// Payload (byte mode) + padding validation
// ---------------------------------------------------------------------------

export function parseByteMode(bits, version) {
  const countBits = version <= 9 ? 8 : 16;
  let p = 0;
  const take = (n) => {
    let v = 0;
    for (let i = 0; i < n; i++) {
      if (p >= bits.length) throw new Error('bit stream exhausted');
      v = (v << 1) | bits[p++];
    }
    return v;
  };
  const mode = take(4);
  if (mode !== 0b0100) return { mode, error: `mode indicator ${mode.toString(2).padStart(4, '0')} is not byte mode` };
  const count = take(countBits);
  const bytes = [];
  for (let i = 0; i < count; i++) bytes.push(take(8));
  return { mode, count, bytes, bitOffset: p, countBits };
}

/** Validate terminator + byte alignment + 0xEC/0x11 pad codewords. */
export function validatePadding(bits, usedBits, dataCodewords) {
  const capacity = dataCodewords * 8;
  const terminator = Math.min(4, capacity - usedBits);
  const problems = [];
  for (let i = 0; i < terminator; i++) if (bits[usedBits + i] !== 0) problems.push(`terminator bit ${i} not 0`);
  const padToByte = (8 - ((usedBits + terminator) % 8)) % 8;
  for (let i = 0; i < padToByte; i++) {
    if (bits[usedBits + terminator + i] !== 0) problems.push(`byte-alignment bit ${i} not 0`);
  }
  const firstPadBit = usedBits + terminator + padToByte;
  const firstPadCw = Math.ceil(firstPadBit / 8);
  let expect = 0xec;
  for (let c = firstPadCw; c < dataCodewords; c++) {
    let v = 0;
    for (let i = 0; i < 8; i++) v = (v << 1) | bits[c * 8 + i];
    if (v !== expect) problems.push(`pad codeword ${c} = 0x${v.toString(16)} expected 0x${expect.toString(16)}`);
    expect = expect === 0xec ? 0x11 : 0xec;
  }
  return { ok: problems.length === 0, problems, terminatorBits: terminator };
}

/** True when every syndrome S_0..S_{t-1} of the block is zero (early exit). */
export function allSyndromesZero(block, t) {
  for (let j = 0; j < t; j++) {
    const root = gfAlpha(j);
    let acc = 0;
    for (let k = 0; k < block.length; k++) acc = gfMul(acc, root) ^ block[k];
    if (acc !== 0) return false;
  }
  return true;
}

/** Concatenate the de-interleaved data codewords in block order. */
export function dataCodewordsOf(de) {
  const out = [];
  for (let b = 0; b < de.blocks.length; b++) {
    for (let i = 0; i < de.dataLens[b]; i++) out.push(de.blocks[b][i]);
  }
  return out;
}

export function bitsOf(cws) {
  const bits = [];
  for (const cw of cws) for (let i = 7; i >= 0; i--) bits.push((cw >> i) & 1);
  return bits;
}

/** Recover (numBlocks, ecLen) from the data by requiring all-zero syndromes. */
export function recoverBlockStructure(codewords, version) {
  const solutions = [];
  let zeroSyndromeCount = 0;
  for (let nb = 1; nb <= 100; nb++) {
    for (let ecLen = 1; ecLen <= 30; ecLen++) {
      const de = deinterleave(codewords, nb, ecLen);
      if (!de) continue;
      if (de.dataEnd < 1) continue;
      let allZero = true;
      for (const blk of de.blocks) {
        if (!allSyndromesZero(blk, ecLen)) {
          allZero = false;
          break;
        }
      }
      if (!allZero) continue;
      zeroSyndromeCount++;
      // A lower-degree generator is always satisfied when the true one is, so
      // the syndrome test alone admits every ecLen <= the real one. Pin the
      // structure down with the payload frame + the spec's padding rules.
      const bits = bitsOf(dataCodewordsOf(de));
      let frame;
      try {
        frame = parseByteMode(bits, version);
      } catch {
        continue;
      }
      if (frame.error || frame.count !== frame.bytes.length) continue;
      if (!validatePadding(bits, frame.bitOffset, de.dataEnd).ok) continue;
      solutions.push({ numBlocks: nb, ecLen, dataCodewords: de.dataEnd, frame });
    }
  }
  return { solutions, zeroSyndromeCount };
}

