const FORMAT_COPY1 = [
  [8, 0], [8, 1], [8, 2], [8, 3], [8, 4], [8, 5], [8, 7], [8, 8], [7, 8],
  [5, 8], [4, 8], [3, 8], [2, 8], [1, 8], [0, 8],
];
export { FORMAT_COPY1 };

function formatCopy2(size) {
  const pos = [];
  for (let i = 0; i < 8; i++) pos.push([size - 1 - i, 8]);
  for (let i = 8; i < 15; i++) pos.push([8, size - 15 + i]);
  return pos;
}
export { formatCopy2 };

function readBits(m, positions) {
  let v = 0;
  for (let i = 0; i < positions.length; i++) {
    const [x, y] = positions[i];
    if (m[y][x]) v |= 1 << i;
  }
  return v;
}

function versionPositions(size, which) {
  const pos = [];
  for (let k = 0; k < 18; k++) {
    const a = size - 11 + (k % 3);
    const b = Math.floor(k / 3);
    pos.push(which === 'tr' ? [a, b] : [b, a]);
  }
  return pos;
}

function decodeFormatCopy(m, positions) {
  const raw = readBits(m, positions);
  const masked = (raw ^ FORMAT_MASK) & 0x7fff;
  const dec = bchDecode(masked, FORMAT_CODE, 15);
  return {
    raw,
    masked,
    distance: dec.distance,
    data5: dec.codeword >>> 10,
    ec: FORMAT_EC[(dec.codeword >>> 13) & 3],
    mask: (dec.codeword >>> 10) & 7,
    ok: dec.ok,
    exact: dec.exact,
  };
}

